#!/bin/bash
set -e

# Default configuration values
DB_HOST="${DB_HOST:-db}"
DB_PORT="${DB_PORT:-3306}"
DB_NAME="${DB_NAME:-testlink}"
DB_USER="${DB_USER:-testlink}"
DB_PASSWORD="${DB_PASSWORD:-testlink_pass}"
DB_ROOT_PASSWORD="${DB_ROOT_PASSWORD:-root_masterkey}"
DB_TABLE_PREFIX="${DB_TABLE_PREFIX:-}"
TESTLINK_ADMIN_USER="${TESTLINK_ADMIN_USER:-admin}"
TESTLINK_ADMIN_PASSWORD="${TESTLINK_ADMIN_PASSWORD:-admin}"

echo "=================================================="
echo " Starting TestLink Container Initialization       "
echo "=================================================="

# Ensure application persistence directories exist
mkdir -p /var/testlink/upload_area /var/testlink/logs
chown -R www-data:www-data /var/testlink
chmod -R 775 /var/testlink

# Wait until database is accessible and ready
echo "==> Waiting for MariaDB at ${DB_HOST}:${DB_PORT}..."
until mysql -h"${DB_HOST}" -P"${DB_PORT}" -u"${DB_USER}" -p"${DB_PASSWORD}" -e "SELECT 1;" >/dev/null 2>&1; do
    echo "Database not ready yet. Retrying in 2 seconds..."
    sleep 2
done
echo "==> Database connection established successfully."

# Check if tables already exist in the target database
TABLE_COUNT=$(mysql -h"${DB_HOST}" -P"${DB_PORT}" -u"${DB_USER}" -p"${DB_PASSWORD}" "${DB_NAME}" -sN -e "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = '${DB_NAME}';" 2>/dev/null || echo "0")

if [ "${TABLE_COUNT}" -eq 0 ]; then
    echo "==> Empty database detected. Seeding schema and default dataset..."

    # 1. Create tables
    echo "--> Creating tables..."
    sed "s|/\*prefix\*/|${DB_TABLE_PREFIX}|g" /var/www/html/install/sql/mysql/testlink_create_tables.sql | \
        mysql -h"${DB_HOST}" -P"${DB_PORT}" -u"${DB_USER}" -p"${DB_PASSWORD}" "${DB_NAME}"

    # 2. Insert default data
    echo "--> Inserting default data..."
    sed "s|/\*prefix\*/|${DB_TABLE_PREFIX}|g" /var/www/html/install/sql/mysql/testlink_create_default_data.sql | \
        mysql -h"${DB_HOST}" -P"${DB_PORT}" -u"${DB_USER}" -p"${DB_PASSWORD}" "${DB_NAME}"

    # 3. Create UDF function if available
    if [ -f /var/www/html/install/sql/mysql/testlink_create_udf0.sql ]; then
        echo "--> Creating helper user-defined functions..."
        sed "s|YOUR_TL_DBNAME|${DB_NAME}|g" /var/www/html/install/sql/mysql/testlink_create_udf0.sql | \
            mysql -h"${DB_HOST}" -P"${DB_PORT}" -u"root" -p"${DB_ROOT_PASSWORD}" "${DB_NAME}" 2>/dev/null || true
    fi

    # 4. Set custom administrator credentials if overridden
    if [ "${TESTLINK_ADMIN_USER}" != "admin" ] || [ "${TESTLINK_ADMIN_PASSWORD}" != "admin" ]; then
        echo "--> Updating admin account credentials..."
        PASS_MD5=$(php -r "echo md5('${TESTLINK_ADMIN_PASSWORD}');")
        mysql -h"${DB_HOST}" -P"${DB_PORT}" -u"${DB_USER}" -p"${DB_PASSWORD}" "${DB_NAME}" \
            -e "UPDATE ${DB_TABLE_PREFIX}users SET login='${TESTLINK_ADMIN_USER}', password='${PASS_MD5}' WHERE login='admin';"
    fi

    echo "==> Database initialization completed."
else
    echo "==> Database contains ${TABLE_COUNT} existing tables. Skipping initial schema import."
fi

# Write config_db.inc.php
cat <<EOF > /var/www/html/config_db.inc.php
<?php
// Automatically generated by Docker entrypoint
define('DB_TYPE', 'mysql');
define('DB_USER', '${DB_USER}');
define('DB_PASS', '${DB_PASSWORD}');
define('DB_HOST', '${DB_HOST}');
define('DB_NAME', '${DB_NAME}');
define('DB_TABLE_PREFIX', '${DB_TABLE_PREFIX}');
EOF

# Write custom_config.inc.php
cat <<'EOF' > /var/www/html/custom_config.inc.php
<?php
// Custom runtime configuration overrides
$g_repositoryPath = '/var/testlink/upload_area/';
$tlCfg->log_path = '/var/testlink/logs/';
EOF

chown www-data:www-data /var/www/html/config_db.inc.php /var/www/html/custom_config.inc.php
chmod 644 /var/www/html/config_db.inc.php /var/www/html/custom_config.inc.php

echo "==> Configuration generated."
echo "==> Starting web server..."

exec "$@"
